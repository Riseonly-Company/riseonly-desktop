#!/usr/bin/env python3
import fnmatch
import json
import os
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IOS = ROOT.parent / "riseonly-ios" / "Riseonly"
CRATE_MAP = ROOT / "scripts" / "crate-map.json"
BOARD = Path(os.environ.get("RISE_BOARD_DB") or next(iter(sorted(ROOT.glob("*/board.sqlite"))), ROOT / "board.sqlite"))
GEN_HEADER = "// @generated by scripts/gen-mod-tree.py"

IOS_SKIP = {"build", "DerivedData", "Assets.xcassets", "ObjC"}
IOS_TOP = {"Core": ["core"], "Theme": ["core", "theme"], "Utils": ["core", "utils"], "UI": ["core", "ui"],
           "Config": ["config"]}
RUST_KEYWORDS = {
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn",
    "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self",
    "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become",
    "box", "do", "final", "gen", "macro", "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
}
OS_BRANCH = {"macos", "linux", "windows"}
SEAM_TRAIT = re.compile(r"^crates/rise-(platform|media)/src/([^/]+)/\2\.rs$")
DESKTOP_ONLY_PREFIXES = ("core/desktop_platform/",)


def to_rust_name(stem: str) -> str:
    stem = stem.replace("-", "_")
    stem = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", stem)
    stem = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", stem)
    stem = re.sub(r"[^A-Za-z0-9_]", "_", stem)
    stem = re.sub(r"_+", "_", stem).strip("_").lower()
    if not stem or stem[0].isdigit():
        stem = "n_" + stem
    if stem in RUST_KEYWORDS:
        stem += "_"
    return stem


def mirror(rel: Path) -> str:
    parts = list(rel.parts)
    head = IOS_TOP.get(parts[0]) if len(parts) > 1 else None
    if head is not None:
        parts = parts[1:]
    dirs = [to_rust_name(p) for p in parts[:-1]]
    return "/".join((head or []) + dirs + [to_rust_name(Path(parts[-1]).stem) + ".rs"])


class CrateMap:

    def __init__(self, path: Path):
        raw = json.loads(path.read_text(encoding="utf-8"))
        self.default = raw.get("default") or "riseonly"
        self.src: dict[str, str] = {}
        self.prefix: dict[str, str] = {}
        self.mounts: dict[str, list[tuple[str, str]]] = {}
        for name, spec in (raw.get("crates") or {}).items():
            src = spec.get("src") or spec["dir"].rstrip("/") + "/src"
            self.src[name] = src.rstrip("/")
            if spec.get("prefix"):
                self.prefix[name] = spec["prefix"].strip("/")
                extra = {k.strip("/"): v.strip("/") for k, v in (spec.get("mounts") or {}).items()}
                self.mounts[name] = [(self.prefix[name], "")] + sorted(extra.items())
        self.rules = [(r["prefix"].strip("/"), r["crate"]) for r in raw.get("rules") or []]
        self.files = dict(raw.get("files") or {})
        self.skip = set(raw.get("skip") or [])
        self.kits = sorted(
            ((name, pre) for name, ms in self.mounts.items() for pre, _ in ms), key=lambda kv: -len(kv[1])
        )

    def crate_for(self, logical: str) -> str:
        if logical in self.files:
            return self.files[logical]
        parts = logical.split("/")
        for pre, crate in self.rules:
            pp = pre.split("/")
            if len(parts) > len(pp) and all(fnmatch.fnmatchcase(a, b) for a, b in zip(parts, pp)):
                return crate
        for name, pre in self.kits:
            if logical.startswith(pre + "/"):
                return name
        return self.default

    def physical(self, path: str) -> str:
        if path.startswith(("crates/", "app/")):
            return path
        crate = self.crate_for(path)
        for pre, sub in sorted(self.mounts.get(crate, []), key=lambda kv: -len(kv[0])):
            if path.startswith(pre + "/"):
                rel = path[len(pre) + 1:]
                return f"{self.src[crate]}/{sub}/{rel}" if sub else f"{self.src[crate]}/{rel}"
        return f"{self.src[crate]}/{path}"

    def logical_roots(self) -> list[tuple[str, str, tuple[str, ...]]]:
        out = [(self.src[self.default], "", ())]
        for name, ms in self.mounts.items():
            if name == self.default:
                continue
            subs = tuple(sub for _, sub in ms if sub)
            for pre, sub in ms:
                src = f"{self.src[name]}/{sub}" if sub else self.src[name]
                out.append((src, pre + "/", () if sub else subs))
        return out


def load_board(cmap: CrateMap) -> tuple[dict[str, str], set[str], set[str]] | None:
    if not BOARD.is_file():
        return None
    db = sqlite3.connect(f"file:{BOARD}?mode=ro", uri=True, timeout=30)
    try:
        twins, na = {}, set()
        for ios, kt, status in db.execute(
                "SELECT ios_path, kt_path, status FROM files WHERE ios_path LIKE 'Riseonly/%'"):
            phys = cmap.physical(kt)
            twins[ios[len("Riseonly/"):]] = phys
            if status == "na":
                na.add(phys)
        extra = {cmap.physical(kt.split()[0]) for (kt,) in db.execute(
            "SELECT kt_path FROM task_files WHERE ios_path IS NULL AND kt_path IS NOT NULL") if kt.strip()}
    finally:
        db.close()
    return twins, na, extra


def ios_files() -> list[Path]:
    out = []
    for path in IOS.rglob("*.swift"):
        rel = path.relative_to(IOS)
        if any(p in IOS_SKIP or p.startswith(".") or p.endswith(".lproj") for p in rel.parts):
            continue
        out.append(rel)
    return out


def is_generated(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            return f.read(len(GEN_HEADER)) == GEN_HEADER
    except OSError:
        return False


def desktop_files(cmap: CrateMap) -> dict[str, str]:
    out = {}
    for src, pre, other in cmap.logical_roots():
        base = ROOT / src
        if not base.is_dir():
            continue
        for p in base.rglob("*.rs"):
            rel = p.relative_to(base).as_posix()
            if p.name in ("lib.rs", "mod.rs") or rel in cmap.skip or is_generated(p):
                continue
            if any(rel.startswith(sub + "/") for sub in other):
                continue
            out[f"{src}/{rel}"] = pre + rel
    return out


def desktop_only_by_rule(phys: str, logical: str) -> bool:
    name = phys.rsplit("/", 1)[-1]
    parts = phys.split("/")
    if name.endswith(("_tests.rs", "_hooks.rs", "_hooks_install.rs")):
        return True
    if name[:-3] in OS_BRANCH or any(p in OS_BRANCH for p in parts[:-1]):
        return True
    return bool(SEAM_TRAIT.match(phys)) or logical.startswith(DESKTOP_ONLY_PREFIXES)


def area_of(logical: str) -> str:
    parts = logical.split("/")
    if parts[0] in ("modules", "core") and len(parts) > 2:
        return f"{parts[0]}/{parts[1]}"
    return parts[0] if len(parts) > 1 else "(root)"


def main() -> int:
    if not IOS.is_dir():
        print(f"reference tree not found at {IOS}", file=sys.stderr)
        return 2
    cmap = CrateMap(CRATE_MAP)
    board = load_board(cmap)
    twins, na, attached = board if board else ({}, set(), set())

    reference: dict[str, str] = {}
    logical_of: dict[str, str] = {}
    for rel in ios_files():
        key = rel.as_posix()
        logical = mirror(rel)
        phys = twins.get(key) or cmap.physical(logical)
        reference[phys] = key
        logical_of[phys] = logical

    ours = desktop_files(cmap)
    counted = {p for p in reference if p not in na}
    ported = {p for p in counted if (ROOT / p).is_file()}
    missing = sorted(logical_of[p] for p in counted - ported)
    extra = sorted(
        logical for phys, logical in ours.items()
        if phys not in reference and phys not in attached and not desktop_only_by_rule(phys, logical)
    )

    by_area: dict[str, list[int]] = {}
    for phys in counted:
        slot = by_area.setdefault(area_of(logical_of[phys]), [0, 0])
        slot[1] += 1
        if phys in ported:
            slot[0] += 1

    print(f"{'area':<34} {'ported':>7} {'total':>7}  progress")
    print("-" * 70)
    for area in sorted(by_area, key=lambda a: (-by_area[a][1], a)):
        done, total = by_area[area]
        pct = 100.0 * done / total if total else 0.0
        print(f"{area:<34} {done:>7} {total:>7}  {pct:5.1f}% {'#' * int(pct / 5)}")

    total = len(counted)
    pct = 100.0 * len(ported) / total if total else 0.0
    print("-" * 70)
    print(f"{'TOTAL':<34} {len(ported):>7} {total:>7}  {pct:5.1f}%")
    print(f"na (no desktop counterpart by decision): {len(reference) - total}")
    if board is None:
        print(f"board not found at {BOARD}: mirror rule only, attached desktop-only files are not known")

    if "--list-missing" in sys.argv:
        print(f"\nunported ({len(missing)}), first 80:")
        for f in missing[:80]:
            print(f"  {f}")

    if extra:
        print(f"\n{len(extra)} file(s) with no iOS counterpart and not attached as desktop-only:")
        for f in extra[:40]:
            print(f"  {f}")
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
