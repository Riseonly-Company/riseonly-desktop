import sys
from pathlib import Path

HEADER = "// @generated by scripts/gen-mod-tree.py from scripts/crate-map.json. Do not edit."
BLOCK_BEGIN = "// @generated mod list begin: scripts/gen-mod-tree.py from scripts/crate-map.json. Do not edit."
BLOCK_END = "// @generated mod list end"
VIEW_HEADER = "// @generated by scripts/gen-mod-tree.py from scripts/crate-map.json and scripts/crate-views.json. Do not edit."
MANIFEST_HEADER = "# @generated by scripts/gen-mod-tree.py from scripts/crate-views.json and the manifest of the top crate. Do not edit."
DEPS_BEGIN = "# @generated view crates begin: scripts/gen-mod-tree.py from scripts/crate-views.json. Do not edit."
DEPS_END = "# @generated view crates end"
ALLOW_GLOB = "#[allow(unused_imports)]"
OS_NAMES = ("macos", "linux", "windows")
VIS = {"pub", "pub(crate)", "pub(super)"}
RESERVED = {"mod.rs", "lib.rs", "main.rs", "build.rs"}
MOD_LINE = re.compile(r"\s*(pub(\([a-z]+\))? )?mod [A-Za-z_0-9]+;\s*")
CFG_LINE = re.compile(r"\s*#\[cfg\(.*\)\]\s*")


class Crate:
    def __init__(self, name: str, spec: dict, ws: Path):
        self.name = name
        self.src = ws / spec["src"]
        self.ident = spec["ident"]
        self.below = spec.get("below")
        self.forbid = spec.get("forbid", [])
        self.lib_attrs = spec.get("lib_attrs", [])
        prefix = spec.get("prefix")
        self.prefix = prefix.strip("/") if prefix else None
        extra = {k.strip("/"): v.strip("/") for k, v in (spec.get("mounts") or {}).items()}
        if extra and not self.prefix:
            raise SystemExit(f"crate-map.json: crate {name}: mounts need a prefix")
        if any(not v for v in extra.values()):
            raise SystemExit(f"crate-map.json: crate {name}: a mount needs its own src subdirectory")
        self.mounts = ([(self.prefix, "")] if self.prefix else []) + sorted(extra.items(), key=lambda kv: -len(kv[1]))
        self.reexport = spec.get("reexport", "hub")
        self.lib = spec.get("lib", "generated")
        self.cfg = spec.get("cfg", {})
        self.vis = spec.get("vis", {})
        bad = {k: v for k, v in self.vis.items() if v not in VIS}
        if bad:
            raise SystemExit(f"crate-map.json: crate {name}: bad vis {bad!r}, allowed {sorted(VIS)}")
        if self.reexport not in ("hub", "all") or self.lib not in ("generated", "block"):
            raise SystemExit(f"crate-map.json: crate {name}: bad reexport {self.reexport!r} or lib {self.lib!r}")


class Mount:

    def __init__(self, crate: Crate, prefix: str, sub: str):
        self.crate, self.prefix, self.sub = crate, prefix, sub
        self.name, self.ident = crate.name, crate.ident
        self.present = not sub or any((crate.src / sub).rglob("*.rs"))

    def path(self) -> str:
        return "::".join([self.ident] + (self.sub.split("/") if self.sub else []))


class Map:
    def __init__(self, path: Path, ws: Path):
        data = json.loads(path.read_text())
        self.default = data["default"]
        self.crates = {n: Crate(n, s, ws) for n, s in data["crates"].items()}
        self.rules = data.get("rules", [])
        self.files = data.get("files", {})
        self.skip = set(data.get("skip", []))
        self.kits = sorted(
            (Mount(c, pre, sub) for c in self.crates.values() for pre, sub in c.mounts), key=lambda k: -len(k.prefix)
        )

    def logical(self, crate: Crate, rel: str) -> str | None:
        for pre, sub in crate.mounts:
            if sub and rel.startswith(sub + "/"):
                return f"{pre}/{rel[len(sub) + 1 :]}"
        if crate.prefix:
            return f"{crate.prefix}/{rel}"
        return rel if crate.name == self.default else None

    def crate_for(self, logical: str) -> str:
        if logical in self.files:
            return self.files[logical]
        parts = logical.split("/")
        for rule in self.rules:
            pre = rule["prefix"].rstrip("/").split("/")
            if len(parts) > len(pre) and all(fnmatch.fnmatchcase(p, q) for p, q in zip(parts, pre)):
                return rule["crate"]
        for kit in self.kits:
            if logical.startswith(kit.prefix + "/"):
                return kit.name
        return self.default

    def physical_rel(self, crate: Crate, logical: str) -> str:
        for pre, sub in sorted(crate.mounts, key=lambda kv: -len(kv[0])):
            if logical.startswith(pre + "/"):
                rest = logical[len(pre) + 1 :]
                return f"{sub}/{rest}" if sub else rest
        return logical


def rs_files(crate: Crate) -> dict[str, Path]:
    out = {}
    if not crate.src.is_dir():
        return out
    for p in crate.src.rglob("*.rs"):
        rel = p.relative_to(crate.src).as_posix()
        if p.name == "mod.rs" or rel in RESERVED:
            continue
        out[rel] = p
    return out


def tree_of(files: set[str]) -> dict[str, tuple[set[str], set[str]]]:
    dirs: dict[str, tuple[set[str], set[str]]] = {}
    for rel in files:
        parts = rel.split("/")
        for i in range(len(parts)):
            d = "/".join(parts[:i])
            stems, subs = dirs.setdefault(d, (set(), set()))
            if i == len(parts) - 1:
                stems.add(parts[i][:-3])
            else:
                subs.add(parts[i])
    return dirs


def join(d: str, name: str) -> str:
    return f"{d}/{name}" if d else name


def cfgs_for(crate: Crate | None, d: str, name: str) -> list[str]:
    out = []
    if name in OS_NAMES:
        out.append(f'#[cfg(target_os = "{name}")]')
    if crate is not None and join(d, name) in crate.cfg:
        out.append(f"#[cfg({crate.cfg[join(d, name)]})]")
    return out


def vis_of(crate: Crate | None, d: str, name: str) -> str:
    default = "pub(crate)" if name in OS_NAMES else "pub"
    return crate.vis.get(join(d, name), default) if crate is not None else default


def includes_by_path(owner: Path | None, test_stem: str) -> bool:
    if owner is None or not owner.is_file():
        return False
    return f'#[path = "{test_stem}.rs"]' in owner.read_text()


HOOKS_SUFFIX = "_hooks_install.rs"


def hooks_index(m: Map, crate: Crate, files: dict[str, Path]) -> list[str]:
    if crate.name != m.default:
        return []
    calls = []
    for rel in sorted(files):
        name = rel.rsplit("/", 1)[-1]
        if not name.endswith(HOOKS_SUFFIX) or rel in m.skip:
            continue
        topic = name[: -len(HOOKS_SUFFIX)]
        segs = rel[:-3].split("/")
        for seg in segs:
            if seg in OS_NAMES:
                calls.append(f'    #[cfg(target_os = "{seg}")]')
        calls.append(f"    crate::{'::'.join(segs)}::install_{topic}_hooks();")
    out = ["/// Installs every feature hook slot (files named <topic>_hooks_install.rs). Called first by the app."]
    if not calls:
        return out + ["pub fn install_feature_hooks() {}"]
    out.append("pub fn install_feature_hooks() {")
    out += calls
    out.append("}")
    return out


def kit_module(crate: Crate, rel: str) -> bool:
    if (crate.src / f"{rel}.rs").is_file():
        return True
    folder = crate.src / rel
    return folder.is_dir() and any(p.name != "mod.rs" for p in folder.rglob("*.rs"))


def kit_uses(m: Map, d: str, defined: set[str]) -> list[tuple[list[str], str]]:
    uses = []
    for kit in m.kits:
        if not kit.present:
            continue
        if d == kit.prefix or d.startswith(kit.prefix + "/"):
            rel = m.physical_rel(kit.crate, d) if d != kit.prefix else kit.sub
            if rel and not kit_module(kit.crate, rel):
                continue
            path = "::".join([kit.ident] + (rel.split("/") if rel else []))
            uses.append(([], f"pub use {path}::*;"))
            continue
        parent, _, name = kit.prefix.rpartition("/")
        if parent == d and name not in defined:
            path = kit.path()
            uses.append(([], f"pub use {path};" if path.endswith("::" + name) else f"pub use {path} as {name};"))
    return uses


def mod_block(m: Map, crate: Crate, d: str, own: dict, files: dict[str, Path], mounts: set[str]) -> list[str]:
    stems, subs = own.get(d, (set(), set()))
    subs = set(subs) | {s for s in mounts if s not in stems}
    hub = d.rsplit("/", 1)[-1] if d else None
    mods, uses = [], []

    for stem in sorted(stems):
        if stem.endswith("_tests"):
            owner_stem = stem[: -len("_tests")]
            owner = files.get(join(d, f"{owner_stem}.rs"))
            if not includes_by_path(owner, stem):
                mods.append((["#[cfg(test)]"] + cfgs_for(crate, d, owner_stem), f"mod {stem};"))
            continue
        mods.append((cfgs_for(crate, d, stem), f"{vis_of(crate, d, stem)} mod {stem};"))
    for sub in subs:
        mods.append((cfgs_for(crate, d, sub), f"{vis_of(crate, d, sub)} mod {sub};"))
    mods.sort(key=lambda item: item[1].split("mod ", 1)[1])

    if crate.reexport == "all" and d:
        for cfg, item in mods:
            name = item.split("mod ", 1)[1].rstrip(";")
            if not name.endswith("_tests"):
                uses.append((cfg, f"{vis_of(crate, d, name)} use self::{name}::*;"))
    elif hub and hub in stems:
        uses.append(([], f"{vis_of(crate, d, hub)} use self::{hub}::*;"))

    if d and d.rsplit("/", 1)[-1] not in OS_NAMES:
        for name in OS_NAMES:
            if name in stems or name in subs:
                uses.append((cfgs_for(crate, d, name), f"use self::{name} as os;"))

    if crate.name == m.default:
        uses += sorted(kit_uses(m, d, set(stems) | subs), key=lambda item: item[1])

    lines = []
    for block in (mods, uses):
        for cfg, item in block:
            lines += cfg
            lines.append(item)
        if block:
            lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def render(m: Map, crate: Crate, d: str, own: dict, files: dict[str, Path], mounts: set[str],
           current: str | None) -> str:
    block = mod_block(m, crate, d, own, files, mounts)
    if d == "" and crate.lib == "block":
        return splice_block(current or "", block)
    lines = [HEADER]
    if d == "":
        lines += crate.lib_attrs
    lines.append("")
    if block:
        lines += block + [""]
    if d == "":
        index = hooks_index(m, crate, files)
        if index:
            lines += index + [""]
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def splice_block(text: str, block: list[str]) -> str:
    wanted = [BLOCK_BEGIN] + block + [BLOCK_END]
    lines = text.splitlines()
    if BLOCK_BEGIN in lines and BLOCK_END in lines:
        a, b = lines.index(BLOCK_BEGIN), lines.index(BLOCK_END)
        out = lines[:a] + wanted + lines[b + 1 :]
        return "\n".join(out).rstrip("\n") + "\n"
    out, at = [], None
    for line in lines:
        if MOD_LINE.fullmatch(line):
            while out and CFG_LINE.fullmatch(out[-1]):
                out.pop()
            if at is None:
                at = len(out)
            continue
        out.append(line)
    if at is None:
        at = 0
        while at < len(out) and (out[at].startswith("//!") or out[at].startswith("#![") or not out[at].strip()):
            at += 1
    out = out[:at] + wanted + out[at:]
    cleaned: list[str] = []
    for line in out:
        if not line.strip() and cleaned and not cleaned[-1].strip():
            continue
        cleaned.append(line)
    i = cleaned.index(BLOCK_END)
    if i + 1 < len(cleaned) and cleaned[i + 1].strip():
        cleaned.insert(i + 1, "")
    j = cleaned.index(BLOCK_BEGIN)
    if j > 0 and cleaned[j - 1].strip():
        cleaned.insert(j, "")
    return "\n".join(cleaned).strip("\n") + "\n"


class View:
    def __init__(self, name: str, spec: dict, ws: Path):
        self.name = name
        self.dir = ws / spec["dir"]
        self.ident = spec.get("ident", name.replace("-", "_"))
        self.deps = list(spec.get("deps", []))


class Views:
    def __init__(self, path: Path, ws: Path):
        data = json.loads(path.read_text())
        self.top = data["top"]
        self.crates = {n: View(n, s, ws) for n, s in data["crates"].items()}
        self.rules = data.get("rules", [])
        self.files = data.get("files", {})
        if self.top not in self.crates:
            raise SystemExit(f"crate-views.json: top crate {self.top} is not listed in crates")
        for view in self.crates.values():
            for dep in view.deps:
                if dep not in self.crates:
                    raise SystemExit(f"crate-views.json: crate {view.name}: unknown dep {dep}")
        named = {r["view"] for r in self.rules} | set(self.files.values())
        unknown = sorted(named - set(self.crates))
        if unknown:
            raise SystemExit(f"crate-views.json: rules or files name unknown crates {unknown}")
        self.below: dict[str, set[str]] = {}
        self.order: list[str] = []
        for name in self.crates:
            self.visit(name, [])
        idents = [v.ident for v in self.crates.values()]
        if len(set(idents)) != len(idents):
            raise SystemExit("crate-views.json: two crates share an ident")

    def visit(self, name: str, trail: list[str]) -> set[str]:
        if name in self.below:
            return self.below[name]
        if name in trail:
            raise SystemExit(f"crate-views.json: dependency cycle {' -> '.join(trail + [name])}")
        out: set[str] = set()
        for dep in self.crates[name].deps:
            out.add(dep)
            out |= self.visit(dep, trail + [name])
        self.below[name] = out
        self.order.append(name)
        return out

    def view_of(self, logical: str, known: dict[str, Path]) -> str:
        if logical in self.files:
            return self.files[logical]
        if logical.endswith("_tests.rs"):
            owner = logical[: -len("_tests.rs")] + ".rs"
            if owner in known:
                return self.view_of(owner, known)
        parts = logical.split("/")
        for rule in self.rules:
            pre = rule["prefix"].strip("/").split("/")
            if len(parts) > len(pre) and all(fnmatch.fnmatchcase(p, q) for p, q in zip(parts, pre)):
                return rule["view"]
        return self.top


def use_key(item: tuple[list[str], str]) -> tuple:
    path = item[1].split("use ", 1)[1].rstrip(";").split(" as ")[0]
    segs = path.split("::")
    return (0 if segs[0] == "self" else 1, [(1, "") if s == "*" else (0, s) for s in segs])


def view_block(m: Map, views: Views, view: View, d: str, ctx: dict) -> list[str]:
    crate = m.crates[m.default]
    files = ctx["files"]
    own_stems, _ = ctx["own"][view.name].get(d, (set(), set()))
    _, seen_subs = ctx["seen"][view.name].get(d, (set(), set()))
    owned_dirs = ctx["owned_dirs"][view.name]
    subs = set(seen_subs) | {s for s in ctx["mounts"].get(d, set()) if s not in own_stems}
    subs = {s for s in subs if s not in OS_NAMES or join(d, s) in owned_dirs}
    hub = d.rsplit("/", 1)[-1] if d else None
    ctx["declared"][view.name].add(d)
    mods, uses = [], []

    for stem in sorted(own_stems):
        if stem.endswith("_tests"):
            owner_stem = stem[: -len("_tests")]
            owner = files.get(join(d, f"{owner_stem}.rs"))
            if not includes_by_path(owner, stem):
                mods.append((["#[cfg(test)]"] + cfgs_for(crate, d, owner_stem), f"mod {stem};"))
            continue
        mods.append((cfgs_for(crate, d, stem), f"{vis_of(crate, d, stem)} mod {stem};"))
    mods.sort(key=lambda item: item[1].split("mod ", 1)[1])

    if hub and hub in own_stems:
        uses.append(([], f"{vis_of(crate, d, hub)} use self::{hub}::*;"))
    if d and d.rsplit("/", 1)[-1] not in OS_NAMES:
        for name in OS_NAMES:
            if name in own_stems or name in subs:
                uses.append((cfgs_for(crate, d, name), f"use self::{name} as os;"))
    private = any(seg in OS_NAMES for seg in d.split("/"))
    if d and not private:
        path = d.replace("/", "::")
        for dep in view.deps:
            if d in ctx["declared"][dep]:
                uses.append(([ALLOW_GLOB], f"pub use {views.crates[dep].ident}::{path}::*;"))
    if not any(d in ctx["declared"][dep] for dep in view.deps):
        for cfg, item in kit_uses(m, d, set(own_stems) | subs):
            uses.append((cfg + [ALLOW_GLOB] if item.endswith("::*;") else cfg, item))
    uses.sort(key=use_key)

    lines = []
    for cfg, item in mods:
        lines += cfg
        lines.append(item)
    for sub in sorted(subs):
        child = join(d, sub)
        lines += cfgs_for(crate, d, sub)
        if not d and view.name != views.top and child in owned_dirs:
            lines.append(f'#[path = "{ctx["tree_rel"][view.name]}/{sub}"]')
        body = view_block(m, views, view, child, ctx)
        head = f"{vis_of(crate, d, sub)} mod {sub}"
        if body:
            lines.append(head + " {")
            lines += [("    " + line) if line else line for line in body]
            lines.append("}")
        else:
            lines.append(head + " {}")
    for cfg, item in uses:
        lines += cfg
        lines.append(item)
    return lines


SLOT_STATIC = re.compile(r"^([ \t]*)(pub(?:\([^)]*\))?\s+)?static\s+([A-Z][A-Z0-9_]*)\s*:\s*FeatureHookSlot\s*<", re.M)
SLOT_TYPE = "core/feature_hooks/feature_hooks.rs"


def slot_statics(files: dict[str, Path], own: set[str], ws: Path, problems: list[str]) -> list[str]:
    out = []
    for rel in sorted(own):
        if rel.endswith("_tests.rs"):
            continue
        for hit in SLOT_STATIC.finditer(files[rel].read_text()):
            if hit.group(1):
                continue
            if not hit.group(2):
                problems.append(f"{show(files[rel], ws)}:1: slot {hit.group(3)} is private: declare it pub(crate) static")
                continue
            out.append("crate::" + "::".join(rel[:-3].split("/")) + "::" + hit.group(3))
    return out


def slots_index(views: Views, view: View, ctx: dict) -> list[str]:
    if SLOT_TYPE not in ctx["files"]:
        return []
    own = ctx["slots"][view.name]
    out = ["/// every feature hook slot of this crate and the crates below, with whether it is filled",
           "pub fn feature_hook_slots() -> Vec<(&'static str, bool)> {"]
    if own:
        out += ["    fn state<T>(slot: &'static crate::core::feature_hooks::feature_hooks::FeatureHookSlot<T>) -> (&'static str, bool) {",
                "        (slot.name(), slot.is_installed())",
                "    }"]
    out.append("    let mut slots: Vec<(&'static str, bool)> = Vec::new();" if own or view.deps else "    let slots: Vec<(&'static str, bool)> = Vec::new();")
    for dep in sorted(view.deps):
        out.append(f"    slots.extend({views.crates[dep].ident}::feature_hook_slots());")
    for path in ctx["slots"][view.name]:
        out.append(f"    slots.push(state(&{path}));")
    out += ["    slots", "}"]
    if view.name == views.top:
        out += ["",
                "#[cfg(test)]",
                "mod feature_hook_slots_tests {",
                "    #[test]",
                "    fn install_feature_hooks_fills_every_slot() {",
                "        crate::install_feature_hooks();",
                "        let mut empty: Vec<&str> =",
                "            crate::feature_hook_slots().into_iter().filter(|(_, filled)| !filled).map(|(name, _)| name).collect();",
                "        empty.sort_unstable();",
                "        empty.dedup();",
                "        assert!(empty.is_empty(), \"slots install_feature_hooks() leaves empty: {empty:?}\");",
                "    }",
                "}"]
    return out


def render_view(m: Map, views: Views, view: View, ctx: dict) -> str:
    lines = [VIEW_HEADER] + m.crates[m.default].lib_attrs + [""]
    block = view_block(m, views, view, "", ctx)
    if block:
        lines += block + [""]
    if view.name == views.top:
        index = hooks_index(m, m.crates[m.default], ctx["files"])
        if index:
            lines += index + [""]
    slots = slots_index(views, view, ctx)
    if slots:
        lines += slots + [""]
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


SECTION = re.compile(r"^\[\[?([^\]]+)\]\]?\s*$")
FEATURE_LINE = re.compile(r"^([A-Za-z0-9_-]+)\s*=\s*\[(.*)\]\s*$")
PATH_VALUE = re.compile(r'path\s*=\s*"([^"]*)"')
COPIED = re.compile(r"^(features|lints|dependencies|dev-dependencies|target\..*\.dependencies)$")


def manifest_sections(text: str) -> list[tuple[str, list[str]]]:
    out: list[tuple[str, list[str]]] = [("", [])]
    for line in text.splitlines():
        hit = SECTION.match(line)
        if hit:
            out.append((hit.group(1).strip(), []))
        else:
            out[-1][1].append(line)
    return out


DEP_NAME = re.compile(r"^([A-Za-z0-9_-]+)\s*(?:=|\.)")


def hand_deps(views: Views, top_text: str) -> set[str]:
    out, inside = set(), False
    for name, body in manifest_sections(top_text):
        if not re.match(r"^(dependencies|dev-dependencies|build-dependencies|target\..*\.dependencies)$", name):
            continue
        for line in body:
            if line.strip() == DEPS_BEGIN:
                inside = True
            elif line.strip() == DEPS_END:
                inside = False
            elif not inside:
                hit = DEP_NAME.match(line.strip())
                if hit:
                    out.add(hit.group(1))
    return out - set(views.crates)


def feature_line(line: str, views: Views, deps: list[str], known: set[str]) -> str:
    hit = FEATURE_LINE.match(line)
    if not hit:
        return line
    name = hit.group(1)
    items = [i for i in re.findall(r'"([^"]*)"', hit.group(2)) if "/" not in i or i.split("/", 1)[0] in known]
    if name != "default":
        items += [f"{dep}/{name}" for dep in deps]
    return f"{name} = [" + ", ".join(f'"{i}"' for i in items) + "]"


def dep_lines(views: Views, view: View) -> list[str]:
    out = []
    for dep in sorted(view.deps):
        rel = os.path.relpath(views.crates[dep].dir, view.dir).replace(os.sep, "/")
        out.append(f'{dep} = {{ path = "{rel}", default-features = false }}')
    return out


def render_manifest(views: Views, view: View, top_text: str) -> str:
    top_dir = views.crates[views.top].dir
    known = hand_deps(views, top_text)
    lines = [MANIFEST_HEADER, "", "[package]", f'name = "{view.name}"']
    lines += [f"{key}.workspace = true" for key in ("version", "edition", "rust-version", "license", "publish")]
    for name, body in manifest_sections(top_text):
        if not COPIED.match(name):
            continue
        kept, inside = [], False
        for line in body:
            if line.strip() == DEPS_BEGIN:
                inside = True
            elif line.strip() == DEPS_END:
                inside = False
            elif not inside and line.strip() and not line.lstrip().startswith("#"):
                kept.append(line)
        if name == "features":
            kept = [feature_line(line, views, view.deps, known) for line in kept]
        else:
            fixed = []
            for line in kept:
                hit = PATH_VALUE.search(line)
                if hit:
                    rel = os.path.relpath(top_dir / hit.group(1), view.dir).replace(os.sep, "/")
                    line = line[: hit.start(1)] + rel + line[hit.end(1) :]
                fixed.append(line)
            kept = fixed
        if name == "dependencies":
            kept = dep_lines(views, view) + kept
        if kept:
            lines += ["", f"[{name}]"] + kept
    return "\n".join(lines) + "\n"


def render_top_manifest(views: Views, text: str) -> str:
    view = views.crates[views.top]
    known = hand_deps(views, text)
    out, section, inside, placed = [], "", False, False
    for line in text.splitlines():
        hit = SECTION.match(line)
        if hit:
            section = hit.group(1).strip()
            out.append(line)
            if section == "dependencies":
                out += [DEPS_BEGIN] + dep_lines(views, view) + [DEPS_END]
                placed = True
            continue
        if line.strip() == DEPS_BEGIN:
            inside = True
            continue
        if line.strip() == DEPS_END:
            inside = False
            continue
        if inside:
            continue
        out.append(feature_line(line, views, view.deps, known) if section == "features" else line)
    if not placed:
        raise SystemExit(f"{view.dir}/Cargo.toml: no [dependencies] section for the view crates")
    return "\n".join(out) + "\n"


def plan_views(m: Map, views: Views, ws: Path, files: dict[str, Path], mounts: dict[str, set[str]],
               wanted: dict[Path, str], problems: list[str]) -> None:
    crate = m.crates[m.default]
    known = {rel: path for rel, path in files.items() if rel not in m.skip}
    assigned = {rel: views.view_of(rel, known) for rel in known}
    for rel in sorted(views.files):
        if rel not in known:
            problems.append(f"scripts/crate-views.json:1: stale entry: {rel} is not a file of {show(crate.src, ws)}")
    own_files: dict[str, set[str]] = {name: set() for name in views.crates}
    for rel, name in assigned.items():
        own_files[name].add(rel)
        if "/" not in rel and name != views.top:
            problems.append(f"{show(files[rel], ws)}:1: a file at the tree root belongs to the top crate {views.top}")
    ctx = {"files": known, "mounts": mounts, "own": {}, "seen": {}, "owned_dirs": {}, "declared": {}, "tree_rel": {},
           "slots": {}}
    for name, view in views.crates.items():
        if not own_files[name]:
            problems.append(f"scripts/crate-views.json:1: crate {name} holds no file")
        seen = set(own_files[name])
        for dep in views.below[name]:
            seen |= own_files[dep]
        ctx["own"][name] = tree_of(own_files[name])
        ctx["seen"][name] = tree_of(seen)
        ctx["owned_dirs"][name] = {d for d in ctx["own"][name] if d}
        ctx["declared"][name] = set()
        ctx["slots"][name] = slot_statics(known, own_files[name], ws, problems)
        ctx["tree_rel"][name] = os.path.relpath(crate.src, view.dir / "src").replace(os.sep, "/")
    for name in views.order:
        for d in ctx["owned_dirs"][name]:
            if d.rsplit("/", 1)[-1] in OS_NAMES:
                for dep in views.below[name]:
                    if d in ctx["owned_dirs"][dep]:
                        problems.append(f"{show(crate.src / d, ws)}:1: an OS layer is split between crates {dep} and {name}")
    top_manifest = views.crates[views.top].dir / "Cargo.toml"
    top_text = top_manifest.read_text() if top_manifest.is_file() else "[dependencies]\n"
    for name in views.order:
        view = views.crates[name]
        wanted[view.dir / "src" / "lib.rs"] = render_view(m, views, view, ctx)
        if name == views.top:
            wanted[top_manifest] = render_top_manifest(views, top_text)
        else:
            wanted[view.dir / "Cargo.toml"] = render_manifest(views, view, top_text)


def stale_views(views: Views | None, ws: Path) -> list[Path]:
    keep = {v.dir.resolve() for v in views.crates.values()} if views else set()
    out = []
    root = ws / "crates"
    if not root.is_dir():
        return out
    for manifest in sorted(root.glob("*/Cargo.toml")):
        if manifest.parent.resolve() in keep:
            continue
        if manifest.read_text().startswith(MANIFEST_HEADER):
            out.append(manifest.parent)
    return out


def plan(m: Map, ws: Path, views: Views | None = None) -> tuple[dict[Path, str], list[str]]:
    problems: list[str] = []
    per_crate = {n: rs_files(c) for n, c in m.crates.items()}
    trees = {n: tree_of(set(f)) for n, f in per_crate.items()}
    wanted: dict[Path, str] = {}

    for name, crate in m.crates.items():
        for rel, path in sorted(per_crate[name].items()):
            if rel in m.skip:
                continue
            logical = m.logical(crate, rel)
            if logical is not None:
                target = m.crate_for(logical)
                if target != name:
                    problems.append(f"{show(path, ws)}:1: misplaced: belongs to crate {target}")
            if crate.forbid:
                pattern = re.compile(r"\b(" + "|".join(map(re.escape, crate.forbid)) + r")\s*::")
                for no, raw in enumerate(path.read_text().splitlines(), 1):
                    code = raw.split("//", 1)[0]
                    if pattern.search(code):
                        problems.append(f"{show(path, ws)}:{no}: forbidden import: {code.strip()}")

        own = trees[name]
        mounts: dict[str, set[str]] = {}
        if name == m.default:
            for kit in (k for k in m.kits if k.present):
                parts = kit.prefix.split("/")
                for i in range(1, len(parts)):
                    mounts.setdefault("/".join(parts[: i - 1]), set()).add(parts[i - 1])
                    mounts.setdefault("/".join(parts[:i]), set())
        if views is not None and name == m.default:
            plan_views(m, views, ws, per_crate[name], mounts, wanted, problems)
            continue
        dirs = set(own) | {""} | set(mounts)
        for d in sorted(dirs):
            target = crate.src / ("lib.rs" if d == "" else f"{d}/mod.rs")
            current = target.read_text() if target.is_file() else None
            wanted[target] = render(m, crate, d, own, per_crate[name], mounts.get(d, set()), current)
    return wanted, problems


def show(path: Path, ws: Path) -> str:
    try:
        return path.relative_to(ws).as_posix()
    except ValueError:
        return path.as_posix()


def stale(m: Map, wanted: dict[Path, str]) -> list[Path]:
    out = []
    for crate in m.crates.values():
        if not crate.src.is_dir():
            continue
        for p in crate.src.rglob("mod.rs"):
            if p not in wanted:
                out.append(p)
    return out


DECL = re.compile(r"(#\[cfg\([^\]]*\)\]\s*)*(pub(\([a-z]+\))? )?(mod|use) [A-Za-z_0-9:{}, *]+")


def removable(p: Path) -> bool:
    text = p.read_text()
    if text.startswith(HEADER):
        return True
    body = " ".join(l.strip() for l in text.splitlines() if l.strip() and not l.strip().startswith("// "))
    if "//!" in body or body.startswith("//"):
        return False
    statements = [s.strip() for s in body.split(";")]
    return all(DECL.fullmatch(s) for s in statements if s)


def prune_dirs(crate: Crate) -> None:
    if not crate.src.is_dir():
        return
    for d in sorted((p for p in crate.src.rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
        if not any(d.iterdir()):
            d.rmdir()


def place(m: Map) -> list[str]:
    moves = []
    taken: dict[tuple[str, str], str] = {}
    for name, crate in m.crates.items():
        for rel, path in sorted(rs_files(crate).items()):
            if rel in m.skip:
                continue
            logical = m.logical(crate, rel)
            if logical is None:
                continue
            target = m.crate_for(logical)
            if target == name:
                continue
            dest_crate = m.crates[target]
            dest_rel = m.physical_rel(dest_crate, logical)
            dest = dest_crate.src / dest_rel
            if dest.exists():
                raise SystemExit(f"cannot move {path}: {dest} exists")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(path), str(dest))
            moves.append(f"{path} -> {dest}")
            src_dir = rel.rsplit("/", 1)[0] if "/" in rel else ""
            dest_dir = dest_rel.rsplit("/", 1)[0] if "/" in dest_rel else ""
            taken.setdefault((name, src_dir), f"{target}\0{dest_dir}")
    for (name, src_dir), where in sorted(taken.items()):
        crate = m.crates[name]
        d = crate.src / src_dir if src_dir else crate.src
        if not src_dir or not d.is_dir() or any(f.name != "mod.rs" for f in d.rglob("*.rs")):
            continue
        target, dest_dir = where.split("\0")
        other = m.crates[target]
        for f in d.rglob("*"):
            if f.is_file() and f.suffix != ".rs":
                dest = other.src / dest_dir / f.relative_to(d)
                if not dest.exists():
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.move(str(f), str(dest))
                    moves.append(f"{f} -> {dest}")
    return moves


def where(m: Map, views: Views | None, ws: Path, asked: list[str]) -> int:
    crate = m.crates[m.default]
    known = {rel: path for rel, path in rs_files(crate).items() if rel not in m.skip}
    missing = 0
    for raw in asked:
        rel = raw
        for prefix in (show(crate.src, ws) + "/", str(crate.src) + "/"):
            if rel.startswith(prefix):
                rel = rel[len(prefix) :]
        if rel in known or rel.endswith(".rs"):
            name = views.view_of(rel, known) if views else m.default
            print(f"{name}\t{rel}" + ("" if rel in known else "\t(new file, by its directory rule)"))
            continue
        needle = raw.replace("::", "/")
        names = sorted({views.view_of(r, known) if views else m.default for r in known if needle in r[:-3]})
        if not names:
            missing += 1
            names = sorted(views.crates) if views else [m.default]
        for name in names:
            print(name)
    return 1 if missing else 0


def main() -> int:
    here = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--ws", "--root", dest="ws", type=Path, default=here)
    ap.add_argument("--map", type=Path)
    ap.add_argument("--views", type=Path)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--place", action="store_true")
    mode.add_argument("--where", nargs="+", metavar="PATH_OR_TEST_FILTER")
    args = ap.parse_args()
    ws = args.ws.resolve()
    m = Map(args.map or ws / "scripts" / "crate-map.json", ws)
    views_path = args.views or ws / "scripts" / "crate-views.json"
    views = Views(views_path, ws) if views_path.is_file() else None

    if args.where:
        return where(m, views, ws, args.where)

    if args.place:
        for line in place(m):
            print("moved", line)

    wanted, problems = plan(m, ws, views)
    gone = stale_views(views, ws)
    drift = [p for p, text in wanted.items() if not p.is_file() or p.read_text() != text]
    hand = [p for p in drift if p.name == "mod.rs" and p.is_file() and not removable(p)]
    drift = [p for p in drift if p not in hand]
    problems += [f"{show(p, ws)}:1: hand code in mod.rs: move it into the file named after the directory"
                 for p in hand]
    old = stale(m, wanted)

    if args.check:
        for p in drift:
            print(f"{show(p, ws)}:1: drift: run gen-mod-tree.py --write")
        for p in old:
            print(f"{show(p, ws)}:1: stale: mod.rs with no source files below")
        for p in gone:
            print(f"{show(p, ws)}:1: stale: view crate that scripts/crate-views.json no longer names")
        for line in problems:
            print(line)
        bad = len(drift) + len(old) + len(gone) + len(problems)
        print(f"gen-mod-tree: {len(wanted)} module files, {bad} problems")
        return 1 if bad else 0

    for p in drift:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p])
        print(f"wrote {show(p, ws)}")
    kept = []
    for p in old:
        if removable(p):
            p.unlink()
            print(f"removed {show(p, ws)}")
        else:
            kept.append(p)
    for p in gone:
        shutil.rmtree(p)
        print(f"removed {show(p, ws)}")
    for crate in m.crates.values():
        prune_dirs(crate)
    for p in kept:
        print(f"{show(p, ws)}:1: hand code in a stale mod.rs: move it into a named file", file=sys.stderr)
    for line in problems:
        print(line, file=sys.stderr)
    return 1 if (kept or problems) else 0


if __name__ == "__main__":
    raise SystemExit(main())
