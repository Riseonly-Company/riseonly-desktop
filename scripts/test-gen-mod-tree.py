#!/usr/bin/env python3
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

GEN = Path(__file__).resolve().parent / "gen-mod-tree.py"
HEADER = "// @generated by scripts/gen-mod-tree.py"

MAP = {
    "version": 1,
    "default": "riseonly",
    "crates": {
        "riseonly": {"dir": "app", "src": "app/src", "ident": "riseonly", "below": None, "forbid": []},
        "rise-ui": {"dir": "crates/rise-ui", "src": "crates/rise-ui/src", "ident": "rise_ui",
                    "prefix": "core/ui", "below": None, "forbid": [], "reexport": "all"},
        "rise-media": {"dir": "crates/rise-media", "src": "crates/rise-media/src", "ident": "rise_media",
                       "prefix": "core/media", "below": None, "forbid": [],
                       "cfg": {"lottie/rlottie_backend": "feature = \"rlottie\""}},
        "rise-platform": {"dir": "crates/rise-platform", "src": "crates/rise-platform/src",
                          "ident": "rise_platform", "below": None, "forbid": []},
    },
    "rules": [],
    "files": {},
    "skip": ["main.rs", "build.rs"],
}

FILES = {
    "app/src/core/settings.rs": "pub struct Settings;\n",
    "crates/rise-ui/src/input_ui/input_ui.rs": "pub struct InputUiState;\n",
    "crates/rise-media/src/lottie/lottie.rs": "pub struct Lottie;\n",
    "crates/rise-media/src/lottie/rlottie_backend.rs": "pub struct Backend;\n",
    "crates/rise-media/src/lottie/rlottie_backend_tests.rs": "#[test]\nfn t() {}\n",
    "crates/rise-platform/src/macos.rs": "pub fn f() {}\n",
    "crates/rise-platform/src/macos_tests.rs": "#[test]\nfn t() {}\n",
    "crates/rise-platform/src/clip/clip.rs": "pub fn read() {}\n",
    "crates/rise-platform/src/clip/macos.rs": "pub fn read() {}\n",
    "crates/rise-platform/src/clip/macos_tests.rs": "#[test]\nfn t() {}\n",
    "crates/rise-platform/src/clip/linux.rs": "pub fn read() {}\n",
    "crates/rise-platform/src/clip/clip_tests.rs": "#[test]\nfn t() {}\n",
    "crates/rise-platform/src/glass/macos/glass_view.rs": "pub struct GlassView;\n",
    "crates/rise-platform/src/glass/macos/glass_view_tests.rs": "#[test]\nfn t() {}\n",
}

HAND_MOD = "crates/rise-platform/src/clip/mod.rs"
HAND_TEXT = "mod clip;\npub use self::clip::*;\n\npub fn hand_code() -> u32 {\n    7\n}\n"

failures: list[str] = []


def check(cond: bool, what: str) -> None:
    print(("ok   " if cond else "FAIL ") + what)
    if not cond:
        failures.append(what)


def tree(root: Path, hand: bool) -> Path:
    for rel, text in FILES.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    if hand:
        (root / HAND_MOD).write_text(HAND_TEXT)
    (root / "map.json").write_text(json.dumps(MAP))
    return root / "map.json"


def run(root: Path, mode: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, "-I", str(GEN), "--ws", str(root), "--map", str(root / "map.json"), mode],
                          capture_output=True, text=True)


def has_block(text: str, lines: list[str]) -> bool:
    got = text.splitlines()
    n = len(lines)
    return any(got[i : i + n] == lines for i in range(len(got) - n + 1))


def test_clean_tree() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        tree(root, hand=False)
        w = run(root, "--write")
        check(w.returncode == 0, f"clean --write rc 0 (got {w.returncode}: {w.stderr.strip()})")
        c = run(root, "--check")
        check(c.returncode == 0, f"clean --check after --write rc 0 (got {c.returncode}: {c.stdout.strip()})")

        lib = (root / "crates/rise-platform/src/lib.rs").read_text()
        check(has_block(lib, ['#[cfg(test)]', '#[cfg(target_os = "macos")]', "mod macos_tests;"]),
              "root OS test macos_tests carries cfg(test) and cfg(target_os = macos)")
        check(has_block(lib, ['#[cfg(target_os = "macos")]', "pub(crate) mod macos;"]), "root OS layer keeps its cfg")

        clip = (root / "crates/rise-platform/src/clip/mod.rs").read_text()
        check(has_block(clip, ['#[cfg(test)]', '#[cfg(target_os = "macos")]', "mod macos_tests;"]),
              "seam OS test clip/macos_tests carries cfg(target_os = macos)")
        check(has_block(clip, ['#[cfg(test)]', "mod clip_tests;"]), "hub test clip_tests carries only cfg(test)")
        check(has_block(clip, ['#[cfg(target_os = "linux")]', "use self::linux as os;"]),
              "seam directory aliases the linux layer as os")

        glass = (root / "crates/rise-platform/src/glass/mod.rs").read_text()
        check(has_block(glass, ['#[cfg(target_os = "macos")]', "pub(crate) mod macos;"]),
              "test inside macos/ is covered by the cfg of its directory module")
        inner = (root / "crates/rise-platform/src/glass/macos/mod.rs").read_text()
        check(has_block(inner, ['#[cfg(test)]', "mod glass_view_tests;"]), "test inside macos/ is declared there")

        lottie = (root / "crates/rise-media/src/lottie/mod.rs").read_text()
        check(has_block(lottie, ['#[cfg(feature = "rlottie")]', "pub mod rlottie_backend;"]),
              "feature cfg on rlottie_backend")
        check(has_block(lottie, ['#[cfg(test)]', '#[cfg(feature = "rlottie")]', "mod rlottie_backend_tests;"]),
              "test of a feature module carries the feature cfg")

        core = (root / "app/src/core/mod.rs").read_text()
        check("pub use rise_ui as ui;" in core.splitlines(), "rise-ui mounted at core/ui")
        check("pub use rise_media as media;" in core.splitlines(), "rise-media mounted at core/media")
        check("pub mod settings;" in core.splitlines(), "default crate keeps its own module next to the mounts")
        ui = (root / "crates/rise-ui/src/input_ui/mod.rs").read_text()
        check("pub use self::input_ui::*;" in ui.splitlines(), "reexport all in the kit directory")


def test_hand_mod_rs() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        tree(root, hand=True)
        c = run(root, "--check")
        out = c.stdout
        check(c.returncode == 1, "--check fails on a hand mod.rs")
        check(f"{HAND_MOD}:1: hand code in mod.rs" in out, "--check names the hand mod.rs as hand code")
        check(f"{HAND_MOD}:1: drift" not in out, "--check does not report the hand mod.rs as drift")
        w = run(root, "--write")
        check(w.returncode == 1, "--write fails on a hand mod.rs")
        check(f"{HAND_MOD}:1: hand code in mod.rs" in w.stderr, "--write names the hand mod.rs")
        check((root / HAND_MOD).read_text() == HAND_TEXT, "--write leaves the hand mod.rs untouched")
        check((root / "crates/rise-platform/src/lib.rs").read_text().startswith(HEADER),
              "--write still writes the other module files")


def test_files_exceptions() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        tree(root, hand=False)
        own = {"core/ui/input_ui/input_ui_extra.rs": "pub struct Extra;\n", "core/ui/tabs/tabs.rs": "pub struct Tabs;\n"}
        data = dict(MAP, files={k: "riseonly" for k in own})
        (root / "map.json").write_text(json.dumps(data))
        for rel, text in own.items():
            p = root / "app/src" / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        w = run(root, "--write")
        check(w.returncode == 0, f"files exceptions --write rc 0 (got {w.returncode}: {w.stderr.strip()})")
        core = (root / "app/src/core/mod.rs").read_text().splitlines()
        check("pub mod ui;" in core and "pub use rise_ui as ui;" not in core,
              "default crate owns core/ui once a files exception lives there")
        ui = (root / "app/src/core/ui/mod.rs").read_text().splitlines()
        check("pub use rise_ui::*;" in ui, "core/ui re-exports the whole kit next to its own modules")
        both = (root / "app/src/core/ui/input_ui/mod.rs").read_text().splitlines()
        check("pub use rise_ui::input_ui::*;" in both, "directory both crates own re-exports the kit module")
        only = (root / "app/src/core/ui/tabs/mod.rs").read_text()
        check("rise_ui" not in only, "directory the kit lacks gets no glob to a missing kit module")


def main() -> int:
    test_clean_tree()
    test_hand_mod_rs()
    test_files_exceptions()
    print(f"test-gen-mod-tree: {len(failures)} failures")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
